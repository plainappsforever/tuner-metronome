// Node fake of the native module (P3 replaces it on devices). Driven by an explicit clock so tests are deterministic:
// `advance(ms)` moves time; captured input is a PCM buffer delivered at real-time pace; the metronome runs the TS
// reference scheduler and emits onBeat with presentation times; the tone is the TS reference synth.
import { Scheduler } from '../engine/metronome/schedule';
import type { Pattern } from '../engine/metronome/pattern';
import type { AudioInfo, InputInfo, InputRead, MetronomeState, MusicAudio, MusicAudioEvents } from './music-audio';

type Listeners = { [K in keyof MusicAudioEvents]: Set<MusicAudioEvents[K]> };

export type FakeOptions = {
  /** Input PCM (mono) and its rate; delivered from startInput on, looped if `loop`. */
  input?: { samples: Float32Array; sampleRate: number; loop?: boolean };
  outputLatencyMs?: number;
  /** Ring buffer capacity in frames (2 s at the input rate by default). */
  ringFrames?: number;
};

export class FakeMusicAudio implements MusicAudio {
  private nowMs = 0;
  private opts: FakeOptions;
  private inputOn = false;
  private inputStartMs = 0;
  private delivered = 0; // input frames handed to JS so far
  private scheduler: Scheduler | null = null;
  private metStartMs = 0;
  private sr = 48000;
  private nextBeat: ReturnType<Scheduler['next']> | null = null;
  private pattern: Pattern | null = null;
  private listeners: Listeners = { onBeat: new Set(), onInterruption: new Set(), onRouteChange: new Set(), onAction: new Set(), onAutoStop: new Set(), onError: new Set() };
  readonly calls: string[] = [];
  tone: { hz: number; sustain: boolean } | null = null;
  haptics = false;

  constructor(opts: FakeOptions = {}) {
    this.opts = opts;
  }

  /** Moves the fake clock; fires onBeat for every click whose presentation time passed. */
  advance(ms: number): void {
    this.nowMs += ms;
    this.flushBeats();
  }

  get now(): number {
    return this.nowMs;
  }

  async startInput(): Promise<InputInfo> {
    this.calls.push('startInput');
    if (!this.opts.input) throw new Error('fake: no input configured');
    this.inputOn = true;
    this.inputStartMs = this.nowMs;
    this.delivered = 0;
    return { sampleRate: this.opts.input.sampleRate, source: 'file', framesPerCallback: 480 };
  }

  async stopInput(): Promise<void> {
    this.calls.push('stopInput');
    this.inputOn = false;
  }

  readInput(maxFrames: number): InputRead {
    const input = this.opts.input;
    if (!this.inputOn || !input) return { data: new Uint8Array(0), dropped: 0 };
    const captured = Math.floor(((this.nowMs - this.inputStartMs) * input.sampleRate) / 1000);
    const ring = this.opts.ringFrames ?? 2 * input.sampleRate;
    let from = this.delivered;
    let dropped = 0;
    if (captured - from > ring) {
      dropped = captured - from - ring;
      from = captured - ring;
    }
    const n = Math.min(maxFrames, captured - from);
    const start = captured - n; // newest frames
    dropped += start - from;
    const out = new Float32Array(n);
    const len = input.samples.length;
    for (let i = 0; i < n; i++) {
      const at = start + i;
      out[i] = input.loop ? input.samples[at % len] : at < len ? input.samples[at] : 0;
    }
    this.delivered = captured;
    return { data: new Uint8Array(out.buffer), dropped };
  }

  async metronomeStart(pattern: Pattern): Promise<void> {
    this.calls.push('metronomeStart');
    this.pattern = pattern;
    this.scheduler = new Scheduler(pattern, this.sr);
    this.metStartMs = this.nowMs;
    this.nextBeat = this.scheduler.next();
  }

  async metronomeUpdate(pattern: Pattern, at: 'beat' | 'bar'): Promise<void> {
    this.calls.push(`metronomeUpdate:${at}`);
    if (!this.scheduler) return;
    this.pattern = pattern;
    // The pending (not yet presented) event is regenerated by the scheduler after the update.
    this.scheduler.update(pattern, at);
  }

  async metronomeStop(): Promise<void> {
    this.calls.push('metronomeStop');
    this.scheduler = null;
    this.nextBeat = null;
  }

  metronomeState(): MetronomeState {
    const sample = Math.floor(((this.nowMs - this.metStartMs) * this.sr) / 1000);
    return { playing: this.scheduler !== null, sample, bar: this.nextBeat?.bar ?? 0, beat: this.nextBeat?.beat ?? 0, bpm: this.pattern?.bpm ?? 0 };
  }

  async toneStart(opts: { hz: number; sustain: boolean }): Promise<void> {
    this.tone = { hz: opts.hz, sustain: opts.sustain };
  }

  async toneStop(): Promise<void> {
    this.tone = null;
  }

  setHaptics(on: boolean): void {
    this.haptics = on;
  }

  setBackground(): void {}

  audioInfo(): AudioInfo {
    return { sampleRate: this.sr, outputLatencyMs: this.opts.outputLatencyMs ?? 20, inputLatencyMs: 10, ioBufferMs: 10, route: 'speaker', underruns: 0, inputSource: this.inputOn ? 'file' : null };
  }

  addListener<K extends keyof MusicAudioEvents>(event: K, listener: MusicAudioEvents[K]) {
    const set = this.listeners[event] as Set<MusicAudioEvents[K]>;
    set.add(listener);
    return { remove: () => set.delete(listener) };
  }

  emit<K extends keyof MusicAudioEvents>(event: K, payload: Parameters<MusicAudioEvents[K]>[0]): void {
    for (const l of this.listeners[event] as Set<(p: typeof payload) => void>) l(payload);
  }

  private flushBeats(): void {
    const latency = this.opts.outputLatencyMs ?? 20;
    while (this.scheduler && this.nextBeat) {
      const e = this.nextBeat;
      const presentationMs = this.metStartMs + (e.sample * 1000) / this.sr + latency;
      if (presentationMs > this.nowMs) return;
      this.emit('onBeat', { bar: e.bar, beat: e.beat, pulse: e.pulse, kind: e.kind, level: e.level, sample: e.sample, presentationMs });
      this.nextBeat = this.scheduler.next();
    }
  }
}
